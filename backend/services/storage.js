// Private storage for driver documents (licence / ID photos).
// - Cloudinary (if CLOUDINARY_URL is set): uploaded as "authenticated" assets, never publicly reachable.
// - Otherwise local disk under backend/uploads (development / free hosting fallback).
// Admins read documents only through an authenticated API endpoint that streams the bytes.
import crypto from 'crypto';
import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const UPLOAD_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'uploads');
const MAX_BYTES = 5 * 1024 * 1024;
const TYPES = {
  'image/jpeg': { ext: 'jpg', magic: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  'image/png': { ext: 'png', magic: (b) => b.subarray(0, 4).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47])) },
  'image/webp': { ext: 'webp', magic: (b) => b.subarray(0, 4).toString() === 'RIFF' && b.subarray(8, 12).toString() === 'WEBP' }
};
const MIME_BY_EXT = Object.fromEntries(Object.entries(TYPES).map(([mime, t]) => [t.ext, mime]));

const useCloudinary = () => Boolean(process.env.CLOUDINARY_URL);
const cloudinary = async () => (await import('cloudinary')).v2; // reads CLOUDINARY_URL itself

/** Validate a base64 image data URL. Returns { buffer, mime } or throws with a user-facing message. */
export function parseImageDataUrl(dataUrl) {
  const match = /^data:(image\/(?:jpeg|png|webp));base64,([A-Za-z0-9+/=\s]+)$/.exec(String(dataUrl || ''));
  if (!match) throw new Error('Documents must be JPEG, PNG or WebP images');
  const buffer = Buffer.from(match[2], 'base64');
  if (buffer.length > MAX_BYTES) throw new Error('Each document must be smaller than 5 MB');
  if (!TYPES[match[1]].magic(buffer)) throw new Error('Document file is not a valid image');
  return { buffer, mime: match[1] };
}

/** Store an image; returns an opaque storage key. */
export async function saveDocument({ buffer, mime }) {
  const { ext } = TYPES[mime];
  if (useCloudinary()) {
    try {
      const cld = await cloudinary();
      const result = await new Promise((resolve, reject) => {
        cld.uploader.upload_stream(
          { type: 'authenticated', folder: 'driver-documents', resource_type: 'image' },
          (error, res) => (error ? reject(error) : resolve(res))
        ).end(buffer);
      });
      return `cld:${result.public_id}.${result.format}`;
    } catch (error) {
      // A broken CLOUDINARY_URL (bad key/secret, wrong cloud name) used to fail every driver application with a 500.
      // ponytail: disk fallback is lost on Render redeploys; fix CLOUDINARY_URL to keep documents durable.
      console.error('Cloudinary upload failed, storing document on disk instead:', error?.message || error);
    }
  }
  await fs.mkdir(UPLOAD_DIR, { recursive: true });
  const filename = `${crypto.randomUUID()}.${ext}`;
  await fs.writeFile(path.join(UPLOAD_DIR, filename), buffer);
  return `local:${filename}`;
}

/** Read a stored image. Returns { buffer, mime }. */
export async function readDocument(key) {
  if (key?.startsWith('cld:')) {
    const cld = await cloudinary();
    const id = key.slice(4);
    const dot = id.lastIndexOf('.');
    const url = cld.utils.private_download_url(id.slice(0, dot), id.slice(dot + 1), {
      type: 'authenticated',
      expires_at: Math.floor(Date.now() / 1000) + 60
    });
    const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
    if (!res.ok) throw new Error('Document not available');
    return { buffer: Buffer.from(await res.arrayBuffer()), mime: MIME_BY_EXT[id.slice(dot + 1)] || 'image/jpeg' };
  }
  const filename = key?.startsWith('local:') ? key.slice(6) : '';
  // Keys are generated by us, but never trust them as paths.
  if (!/^[\w-]+\.(jpg|png|webp)$/.test(filename)) throw new Error('Document not available');
  const buffer = await fs.readFile(path.join(UPLOAD_DIR, filename));
  return { buffer, mime: MIME_BY_EXT[filename.split('.').pop()] };
}
